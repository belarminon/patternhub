<#
Remove tracked node_modules and push a cleanup branch for PR

Usage (run from repo root):
  .\desafio\patternhub\scripts\remove_tracked_node_modules.ps1

This will:
 - create a new branch 'cleanup/remove-node-modules-main-LOCAL'
 - run 'git rm -r --cached' for the frontend node_modules
 - commit the change
 - push the branch to origin (you must have push rights)
 - print the PR creation command/url

Review the changes before pushing. This script does not force-push or rewrite history.
#>

$branch = "cleanup/remove-node-modules-main-LOCAL"

Write-Host "Creating branch $branch" -ForegroundColor Cyan
git checkout -b $branch
if ($LASTEXITCODE -ne 0) { Write-Host "Failed to create branch. Aborting." -ForegroundColor Red; exit 1 }

Write-Host "Removing tracked node_modules (cached) in patternhub-frontend..." -ForegroundColor Cyan
git rm -r --cached patternhub-frontend/node_modules || Write-Host "No tracked node_modules found or already removed." -ForegroundColor Yellow

Write-Host "Adding .gitignore changes and committing..." -ForegroundColor Cyan
git add .gitignore
git commit -m "Remove tracked node_modules and add .gitignore" || Write-Host "Nothing to commit or commit failed." -ForegroundColor Yellow

Write-Host "Pushing branch to origin: $branch" -ForegroundColor Cyan
git push -u origin $branch

Write-Host "Branch pushed. Create a PR from $branch into main via GitHub." -ForegroundColor Green
Write-Host "Example URL: https://github.com/<owner>/<repo>/compare/main...$branch" -ForegroundColor Green

exit 0
